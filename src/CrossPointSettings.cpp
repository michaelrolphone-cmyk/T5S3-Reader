void applyLegacyFrontButtonLayout(CrossPointSettings& settings) {
  switch (static_cast<CrossPointSettings::FRONT_BUTTON_LAYOUT>(settings.frontButtonLayout)) {
    case CrossPointSettings::LEFT_RIGHT_BACK_CONFIRM:
      settings.frontButtonBack = CrossPointSettings::FRONT_HW_LEFT;
      settings.frontButtonConfirm = CrossPointSettings::FRONT_HW_RIGHT;
      settings.frontButtonLeft = CrossPointSettings::FRONT_HW_BACK;
      settings.frontButtonRight = CrossPointSettings::FRONT_HW_CONFIRM;
      break;
    case CrossPointSettings::LEFT_BACK_CONFIRM_RIGHT:
      settings.frontButtonBack = CrossPointSettings::FRONT_HW_CONFIRM;
      settings.frontButtonConfirm = CrossPointSettings::FRONT_HW_LEFT;
      settings.frontButtonLeft = CrossPointSettings::FRONT_HW_BACK;
      settings.frontButtonRight = CrossPointSettings::FRONT_HW_RIGHT;
      break;
    case CrossPointSettings::BACK_CONFIRM_RIGHT_LEFT:
      settings.frontButtonBack = CrossPointSettings::FRONT_HW_BACK;
      settings.frontButtonConfirm = CrossPointSettings::FRONT_HW_CONFIRM;
      settings.frontButtonLeft = CrossPointSettings::FRONT_HW_RIGHT;
      settings.frontButtonRight = CrossPointSettings::FRONT_HW_LEFT;
      break;
    case CrossPointSettings::BACK_CONFIRM_LEFT_RIGHT:
    default:
      settings.frontButtonBack = CrossPointSettings::FRONT_HW_BACK;
      settings.frontButtonConfirm = CrossPointSettings::FRONT_HW_CONFIRM;
      settings.frontButtonLeft = CrossPointSettings::FRONT_HW_LEFT;
      settings.frontButtonRight = CrossPointSettings::FRONT_HW_RIGHT;
      break;
  }
}

void migrateLegacyOpenDyslexicSelection(CrossPointSettings& settings) {
  if (settings.sdFontFamilyName[0] != '\0') {
    return;
  }
  if (settings.fontFamily == CrossPointSettings::OPENDYSLEXIC) {
    strncpy(settings.sdFontFamilyName, "OpenDyslexic", sizeof(settings.sdFontFamilyName) - 1);
    settings.sdFontFamilyName[sizeof(settings.sdFontFamilyName) - 1] = '\0';
    settings.fontFamily = CrossPointSettings::NOTOSERIF;
  }
}

bool looksLikeSettingsJson(const String& json) {
  if (json.isEmpty()) {
    return false;
  }
  const char* p = json.c_str();
  size_t printable = 0;
  size_t checked = 0;
  while (*p != '\0' && isspace(static_cast<unsigned char>(*p))) {
    ++p;
    ++checked;
  }
  if (*p != '{') {
    return false;
  }
  for (; *p != '\0'; ++p, ++checked) {
    const unsigned char c = static_cast<unsigned char>(*p);
    if (c == 0xFF || c == 0x00) {
      return false;
    }
    if (c >= 32 || c == '\n' || c == '\r' || c == '\t') {
      ++printable;
    }
  }
  return checked >= 2 && printable * 2 >= checked;
}

void quarantineSettingsJson() {
  Storage.ensureDirectoryExists("/.crosspoint");

  char dest[96];
  const time_t now = time(nullptr);
  if (now > 1600000000) {
    struct tm t = {};
    gmtime_r(&now, &t);
    snprintf(dest, sizeof(dest), "/.crosspoint/settings.json.bak.%04d%02d%02dT%02d%02d%02d",
             t.tm_year + 1900, t.tm_mon + 1, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec);
  } else {
    snprintf(dest, sizeof(dest), "/.crosspoint/settings.json.bak.%lu", static_cast<unsigned long>(millis()));
  }

  if (Storage.exists(dest)) {
    Storage.remove(dest);
  }
  if (Storage.rename(SETTINGS_FILE_JSON, dest)) {
    LOG_ERR("CPS", "Quarantined corrupted settings.json to %s", dest);
    return;
  }

  LOG_ERR("CPS", "Rename of corrupted settings.json failed, deleting");
  Storage.remove(SETTINGS_FILE_JSON);
}

